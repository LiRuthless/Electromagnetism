function P = params()
%PARAMS 电磁赛道 Simulink 模型的全部默认参数（唯一参数来源）。
% 默认值照抄设计基准《数学模型.md》§3.2 / §6.3 / §8，与 em-field-studio
% 代码（src/mathmodel/）一致。单位一律 SI：m, rad, T, A, V, s。
%
% 用法：
%   P = params;            % 全部默认
%   P.kp = 0.8;            % 改参数
%   init([], P);           % 注入 base 工作区供 Simulink 模型使用

% ---- 物理常数与场计算（§2 / §5）----
P.MU0        = 4*pi*1e-7; % 真空磁导率 H/m
P.I          = 0.1;       % 赛道电流幅值 A（界面可调 20–200 mA）
P.R_MIN      = 1e-3;      % 奇异截断距离 m（式 5.4）
P.MAX_DS     = 0.01;      % 圆弧离散最大段长 m（§4.2）
P.CLOSE_SNAP = 0.02;      % 闭环吸合阈值 m（式 4.3）

% ---- 电感响应（§6）----
P.VPP_ANCHOR = 6;         % 标定锚点 Vpp（V，20kHz/100mA 贴线，先验值 5–7）
% 标定系数 k = Vpp_anchor / B_touch（式 6.2–6.4，≈9.75e5 V/T）；
% 内联计算（等同 em_calibK），避免 params 在 addpath 之前被调用时找不到函数
P.k = P.VPP_ANCHOR / (P.MU0*P.I / (2*pi*(0.00025 + 0.003)));
% 默认 4 电感布局（§6.3 表）：L1/R1 主对纵向(感 By)，L2/R2 宽对横向(感 Bx)。
% 列含义：车体系 x, 车体系 y, 高度 h, 敏感轴车体系分量 ax, ay, az（式 6.7/6.8）
P.sensMat = [ -0.050, 0.08, 0.075, 0, 1, 0; ...   % L1 主对·左
               0.050, 0.08, 0.075, 0, 1, 0; ...   % R1 主对·右
              -0.075, 0.08, 0.075, 1, 0, 0; ...   % L2 宽对·左
               0.075, 0.08, 0.075, 1, 0, 0 ];     % R2 宽对·右
P.sensNames = {'L1','R1','L2','R2'};

% ---- 误差公式系数（§8.2，式 8.1 差比和差加权，结构固定、系数可调）----
P.A = 1;  P.B = 1;  P.C = 1;  P.Pcoef = 1;

% ---- PD 控制与差速轮速分配（§8.3，式 8.2–8.5）----
P.kp    = 0.5;    % PD 比例系数
P.kd    = 0.05;   % PD 微分系数（相邻控制步差分 / dt）
P.vBase = 1.0;    % 基础速度 m/s
P.vMax  = 2.0;    % 轮速上限 m/s（限幅 [0, vMax]）
P.w     = 1.5;    % 差速权重 w：内轮变化量 : 外轮变化量 = w : 1

% ---- 电机一阶滞后与差速运动学（§8.4 / §8.5）----
P.tauS = 0.030;   % 电机一阶滞后时间常数 s（0 = 无滞后，瞬时跟随）
P.W    = 0.135;   % 轮距 m
P.dt   = 0.005;   % 控制/积分步长 s（5 ms，与实车一致）

% ---- 初始扰动与终止条件（§8.5，式 8.10）----
P.initE         = 0;      % 初始横向偏差 m（>0 右偏）
P.initPsi       = 0;      % 初始航向角扰动 rad（>0 右偏）
P.errLimit      = 2;      % 失控判停：|Err| 阈值
P.errLimitSteps = 200;    % 失控判停：持续超限步数
P.finishTol     = 0.5;    % 非闭环完赛容差 m（闭环赛道跑一圈即停）
P.stopTime      = 120;    % 仿真时长上限 s（实际由终止判定提前 Stop）

% ---- 默认赛道（track_lib/ 中的函数名）----
P.trackName = 'track_s_curve';
end
